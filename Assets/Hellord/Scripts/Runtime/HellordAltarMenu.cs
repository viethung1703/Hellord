        /// <summary>real glyph-pixel bbox columns (l..r, relative to the text origin) of a SMALL-font string.</summary>
        static void AmBb(string s, out int l, out int r)
        {
            l = int.MaxValue; r = -1; int cx = 0, n = 0;
            foreach (char c in s)
            {
                if (n > 0) cx++; n++; if (c == ' ') { cx += 3; continue; }
                var g = MtGlyph(false, c); if (g == null) continue; int gw = 0; foreach (var row in g) gw = Mathf.Max(gw, row.Length);
                for (int j = 0; j < g.Length; j++) for (int i = 0; i < g[j].Length; i++) if (g[j][i] == '#') { l = Mathf.Min(l, cx + i); r = Mathf.Max(r, cx + i); }
                cx += gw;
            }
            if (r < 0) { l = 0; r = -1; }
        }
